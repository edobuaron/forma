-- Running: standalone runs and runs inside a mixed workout, manually logged.
--
-- * Runs live in their own tables, never in set_logs. Lifting volume, working-set counts, comparisons,
--   progression and records all read set_logs / set_history, so a run can't leak into any of them.
-- * template_runs is the plan: a run prescribed by time, by distance, as intervals (repeat count, work
--   time or distance, optional recovery time), or open (no target). session_runs is what happened, with
--   the plan copied into `prescribed` when the workout starts, exactly like session_exercises. Planned
--   targets and actual results are separate columns and never fill each other in.
-- * Actual results: duration (required to complete a run), distance (optional; missing stays null),
--   perceived effort 1–10 (optional), intervals done (optional), outdoor/treadmill (optional; null = not
--   recorded), notes. Distances are metres, durations seconds. Pace is never stored: it's derived only
--   when both distance and duration exist. No calories, GPS or heart rate.
-- * Runs share the position space of their workout's exercises, so a mixed workout keeps its order.
-- * profiles.distance_unit ('km' / 'mi') is how distances are shown and typed; storage is always metres.
--
-- Apply after 014 (015 and 017 are independent). Existing rows are unchanged: no existing workout or
-- program gains a run, and every function below behaves as before for workouts without runs.

alter table public.profiles
  add column distance_unit text not null default 'km' check (distance_unit in ('km', 'mi'));

-- ---------- the plan ----------
create table public.template_runs (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  template_id uuid not null references public.workout_templates(id) on delete cascade,
  position integer not null default 0,
  name text not null default 'Run' check (char_length(btrim(name)) between 1 and 120),
  -- null = either / not specified
  setting text check (setting in ('outdoor', 'treadmill')),
  target_kind text not null default 'open' check (target_kind in ('open', 'time', 'distance', 'intervals')),
  target_duration_s integer check (target_duration_s between 1 and 86400),
  target_distance_m numeric(8,1) check (target_distance_m > 0 and target_distance_m <= 500000),
  interval_count smallint check (interval_count between 1 and 50),
  interval_work_s integer check (interval_work_s between 1 and 7200),
  interval_work_m numeric(8,1) check (interval_work_m > 0 and interval_work_m <= 50000),
  interval_recovery_s integer check (interval_recovery_s between 0 and 3600),
  optional boolean not null default false,
  notes text check (notes is null or char_length(notes) <= 1000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  -- Exactly the fields of the chosen target kind; intervals have either a work time or a work distance.
  constraint template_runs_target_shape check (
    (target_kind = 'open' and target_duration_s is null and target_distance_m is null
       and interval_count is null and interval_work_s is null and interval_work_m is null and interval_recovery_s is null)
    or (target_kind = 'time' and target_duration_s is not null and target_distance_m is null
       and interval_count is null and interval_work_s is null and interval_work_m is null and interval_recovery_s is null)
    or (target_kind = 'distance' and target_distance_m is not null and target_duration_s is null
       and interval_count is null and interval_work_s is null and interval_work_m is null and interval_recovery_s is null)
    or (target_kind = 'intervals' and interval_count is not null and (interval_work_s is null) <> (interval_work_m is null)
       and target_duration_s is null and target_distance_m is null))
);
create index template_runs_template_idx on public.template_runs(template_id, position);
create index template_runs_user_idx on public.template_runs(user_id);
create trigger template_runs_touch before update on public.template_runs
  for each row execute function public.touch_updated_at();

-- ---------- what happened ----------
create table public.session_runs (
  id uuid primary key,                       -- generated by the client, so autosave retries are idempotent
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  session_id uuid not null references public.workout_sessions(id) on delete cascade,
  template_run_id uuid references public.template_runs(id) on delete set null,
  position integer not null default 0,
  name text not null default 'Run' check (char_length(btrim(name)) between 1 and 120),
  -- the plan at the time of the workout: {target_kind, target_duration_s, target_distance_m, interval_count,
  -- interval_work_s, interval_work_m, interval_recovery_s, setting, optional, notes}; {} = no plan
  prescribed jsonb not null default '{}'::jsonb check (jsonb_typeof(prescribed) = 'object'),
  setting text check (setting in ('outdoor', 'treadmill')),
  duration_s integer check (duration_s between 1 and 86400),
  distance_m numeric(9,1) check (distance_m > 0 and distance_m <= 500000),
  effort smallint check (effort between 1 and 10),
  intervals_done smallint check (intervals_done between 0 and 50),
  notes text check (notes is null or char_length(notes) <= 1000),
  completed boolean not null default false,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  -- A completed run has a duration. Faster than 11 m/s (≈1:31 per km) is an entry error, not a run.
  constraint session_runs_completed_duration check (not completed or duration_s is not null),
  constraint session_runs_plausible_speed check (not completed or distance_m is null or distance_m <= duration_s * 11)
);
create index session_runs_session_idx on public.session_runs(session_id, position);
create index session_runs_user_idx on public.session_runs(user_id);
create index session_runs_template_run_idx on public.session_runs(template_run_id);
create trigger session_runs_touch before update on public.session_runs
  for each row execute function public.touch_updated_at();

-- Children belong to their parent's owner (same rule as assert_same_owner for the lifting tables).
create or replace function public.assert_run_owner() returns trigger
language plpgsql security definer set search_path = public as $$
declare owner uuid;
begin
  if tg_table_name = 'template_runs' then
    select user_id into owner from workout_templates where id = new.template_id;
    if owner is distinct from new.user_id then raise exception 'template owner mismatch'; end if;
  elsif tg_table_name = 'session_runs' then
    select user_id into owner from workout_sessions where id = new.session_id;
    if owner is distinct from new.user_id then raise exception 'session owner mismatch'; end if;
    if new.template_run_id is not null then
      select user_id into owner from template_runs where id = new.template_run_id;
      if owner is distinct from new.user_id then raise exception 'template run owner mismatch'; end if;
    end if;
  end if;
  return new;
end $$;
revoke execute on function public.assert_run_owner() from public, anon, authenticated;
create trigger template_runs_owner before insert or update on public.template_runs
  for each row execute function public.assert_run_owner();
create trigger session_runs_owner before insert or update on public.session_runs
  for each row execute function public.assert_run_owner();

do $$
declare t text;
begin
  foreach t in array array['template_runs', 'session_runs'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('create policy "own rows: select" on public.%I for select to authenticated using (user_id = (select auth.uid()))', t);
    execute format('create policy "own rows: insert" on public.%I for insert to authenticated with check (user_id = (select auth.uid()))', t);
    execute format('create policy "own rows: update" on public.%I for update to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()))', t);
    execute format('create policy "own rows: delete" on public.%I for delete to authenticated using (user_id = (select auth.uid()))', t);
  end loop;
end $$;

-- The plan part of a template run, as copied into session_runs.prescribed.
create or replace function public.run_prescription(r public.template_runs) returns jsonb
language sql immutable set search_path = public as $$
  select jsonb_strip_nulls(jsonb_build_object(
    'target_kind', r.target_kind, 'target_duration_s', r.target_duration_s, 'target_distance_m', r.target_distance_m,
    'interval_count', r.interval_count, 'interval_work_s', r.interval_work_s, 'interval_work_m', r.interval_work_m,
    'interval_recovery_s', r.interval_recovery_s, 'setting', r.setting, 'optional', r.optional, 'notes', r.notes));
$$;
revoke execute on function public.run_prescription(public.template_runs) from public, anon;
grant execute on function public.run_prescription(public.template_runs) to authenticated;

-- ---------- starting a workout ----------
-- Same as migration 014, plus the template's runs (no actual values; the setting is pre-filled only
-- when the plan names it, and stays editable).
create or replace function public.start_workout_on(
  p_template_id uuid default null, p_name text default null, p_started_at timestamptz default null
) returns uuid
language plpgsql security invoker set search_path = public as $$
declare
  sid uuid;
  t workout_templates%rowtype;
  te record;
  tr template_runs%rowtype;
  seid uuid;
  bw numeric;
  v_at timestamptz := coalesce(p_started_at, now());
begin
  if auth.uid() is null then raise exception 'not authenticated'; end if;
  if v_at > now() + interval '5 minutes' then raise exception 'future_date'; end if;
  select id into sid from workout_sessions where user_id = auth.uid() and status = 'in_progress';
  if sid is not null then
    raise exception 'workout_in_progress' using detail = sid::text;
  end if;
  select bodyweight_kg into bw from profiles where id = auth.uid();

  if p_template_id is null then
    insert into workout_sessions (name, bodyweight_kg, started_at)
    values (coalesce(nullif(trim(p_name), ''), 'Workout'), bw, v_at) returning id into sid;
    return sid;
  end if;

  select * into t from workout_templates where id = p_template_id;
  if not found then raise exception 'template not found'; end if;

  insert into workout_sessions (template_id, program_id, name, bodyweight_kg, started_at)
  values (t.id, t.program_id, coalesce(nullif(trim(p_name), ''), t.name), bw, v_at) returning id into sid;

  for te in
    select x.*, e.track_sides,
           case when e.default_attachment_state = 'attachment' and a.archived_at is not null then null else e.default_attachment_state end as att_state,
           case when a.archived_at is null then e.default_attachment_id end as att_id
    from template_exercises x
    join exercises e on e.id = x.exercise_id
    left join attachments a on a.id = e.default_attachment_id
    where x.template_id = t.id order by x.position
  loop
    insert into session_exercises (session_id, exercise_id, template_exercise_id, position, prescribed,
                                   track_sides, attachment_state, attachment_id)
    values (sid, te.exercise_id, te.id, te.position,
            jsonb_build_object('sets', te.sets, 'rep_min', te.rep_min, 'rep_max', te.rep_max,
                               'rest_s', te.rest_s, 'target_rir', te.target_rir,
                               'optional', te.optional, 'notes', te.notes,
                               'warmup_sets', te.warmup_sets, 'drop_segments', te.drop_segments,
                               'drop_scope', te.drop_scope, 'target_rpe', te.target_rpe, 'tempo', te.tempo,
                               'target_weight_kg', te.target_weight_kg, 'per_side', te.per_side,
                               'superset_group', te.superset_group),
            te.track_sides, te.att_state, te.att_id)
    returning id into seid;
    insert into set_logs (session_id, session_exercise_id, position, kind, sided)
    select sid, seid, g - 1, 'warmup', te.track_sides from generate_series(1, te.warmup_sets) g;
    insert into set_logs (session_id, session_exercise_id, position, kind, sided)
    select sid, seid, te.warmup_sets + g - 1, 'working', te.track_sides from generate_series(1, te.sets) g;
  end loop;

  for tr in select * from template_runs where template_id = t.id order by position loop
    insert into session_runs (id, session_id, template_run_id, position, name, prescribed, setting)
    values (gen_random_uuid(), sid, tr.id, tr.position, tr.name, public.run_prescription(tr), tr.setting);
  end loop;
  return sid;
end $$;

-- A standalone run: a workout named "Run" holding one empty run.
create or replace function public.start_run_on(p_started_at timestamptz default null, p_name text default null)
returns uuid
language plpgsql security invoker set search_path = public as $$
declare sid uuid;
begin
  sid := public.start_workout_on(null, coalesce(nullif(btrim(p_name), ''), 'Run'), p_started_at);
  insert into session_runs (id, session_id, position, name) values (gen_random_uuid(), sid, 0, 'Run');
  return sid;
end $$;
revoke execute on function public.start_run_on(timestamptz, text) from public, anon;
grant execute on function public.start_run_on(timestamptz, text) to authenticated;

-- ---------- finishing ----------
-- Same as migration 013, except: a completed run counts as work (a run-only workout can be finished),
-- a completed run needs a plausible duration, and runs not marked complete are removed like unfinished
-- sets. A run is never completed or given values here.
create or replace function public.finish_workout(p_session_id uuid, p_notes text, p_ended_at timestamptz, p_shortfall_reason text default null)
returns void language plpgsql security invoker set search_path = public as $$
declare s workout_sessions%rowtype;
begin
  if auth.uid() is null then raise exception 'not authenticated'; end if;
  select * into s from workout_sessions where id = p_session_id for update;
  if not found then raise exception 'Workout not found.'; end if;
  if s.status = 'completed' then return; end if; -- safe retry after a lost response
  if s.status <> 'in_progress' then raise exception 'This workout cannot be completed.'; end if;
  if p_ended_at is null or p_ended_at < s.started_at then raise exception 'Invalid workout end time.'; end if;
  perform id from session_exercises where session_id = p_session_id for update;
  perform id from set_logs where session_id = p_session_id for update;
  perform id from session_runs where session_id = p_session_id for update;
  if not exists (select 1 from set_logs where session_id = p_session_id and completed)
     and not exists (select 1 from session_runs where session_id = p_session_id and completed) then
    raise exception 'Complete at least one set or run first.';
  end if;
  if exists (
    select 1 from set_logs l join session_exercises se on se.id = l.session_exercise_id
    join exercises e on e.id = se.exercise_id
    where l.session_id = p_session_id and l.completed and (
      (not l.sided and (l.reps is null or l.reps < 1
        or (e.load_type = 'assisted' and l.assistance_kg is null)
        or (e.load_type = 'external' and l.weight_kg is null)))
      or (l.sided and l.left_completed and (l.left_reps is null or l.left_reps < 1
        or (e.load_type = 'assisted' and l.left_assistance_kg is null)
        or (e.load_type = 'external' and l.left_weight_kg is null)))
      or (l.sided and l.right_completed and (l.right_reps is null or l.right_reps < 1
        or (e.load_type = 'assisted' and l.right_assistance_kg is null)
        or (e.load_type = 'external' and l.right_weight_kg is null))))
  ) then raise exception 'A completed set is missing reps or load. Correct it before finishing.'; end if;
  if exists (
    select 1 from set_logs d join set_logs p on p.id = d.drop_parent_id
    where d.session_id = p_session_id and d.completed and not p.completed
  ) then raise exception 'A drop is logged under a set that is not completed. Complete or remove it before finishing.'; end if;
  delete from set_logs where session_id = p_session_id and not completed;
  delete from session_runs where session_id = p_session_id and not completed;
  update set_logs set left_weight_kg = null, left_assistance_kg = null, left_reps = null, left_rir = null, left_completed_at = null
   where session_id = p_session_id and sided and not left_completed;
  update set_logs set right_weight_kg = null, right_assistance_kg = null, right_reps = null, right_rir = null, right_completed_at = null
   where session_id = p_session_id and sided and not right_completed;
  update workout_sessions set status = 'completed', ended_at = p_ended_at, notes = p_notes, shortfall_reason = p_shortfall_reason
   where id = p_session_id;
end $$;

-- ---------- editing a past workout ----------
-- Same as migration 013, plus:
--  * an exercise may carry `position`, so exercises and runs keep one shared order (array order is the
--    fallback, as before);
--  * p_runs: the workout's complete list of runs [{id, name, position, prescribed, setting, duration_s,
--    distance_m, effort, intervals_done, notes}]. Every run in a saved workout is completed, so each needs
--    a duration. NULL (an older client) leaves the runs untouched.
-- Everything is validated before anything is written, in one transaction.
drop function if exists public.save_session_edit(uuid, jsonb, jsonb);
create or replace function public.save_session_edit(p_session_id uuid, p_session jsonb, p_exercises jsonb, p_runs jsonb default null)
returns void
language plpgsql security invoker set search_path = public as $$
declare
  s workout_sessions%rowtype;
  v_name text := nullif(btrim(p_session->>'name'), '');
  v_start timestamptz := (p_session->>'started_at')::timestamptz;
  v_end timestamptz := (p_session->>'ended_at')::timestamptz;
  e jsonb;
  e_pos bigint;
  st jsonb;
  st_pos bigint;
  rn jsonb;
  rn_pos bigint;
  v_load public.load_type;
  v_ex_name text;
  v_reps integer;
  v_sided boolean;
  v_side text;
  v_l boolean;
  v_r boolean;
  v_kind text;
  v_parent uuid;
  v_dur integer;
  v_dist numeric;
  working_ids uuid[];
  ex_ids uuid[] := '{}';
  set_ids uuid[] := '{}';
  run_ids uuid[] := '{}';
begin
  if auth.uid() is null then raise exception 'not authenticated'; end if;
  select * into s from workout_sessions where id = p_session_id for update;
  if not found then raise exception 'session_not_found'; end if;
  if s.status <> 'completed' then raise exception 'session_not_editable'; end if;
  if v_name is null or v_start is null or v_end is null
     or v_end < v_start + interval '1 minute' or v_end > v_start + interval '600 minutes' then
    raise exception 'invalid_session';
  end if;
  if jsonb_typeof(p_exercises) is distinct from 'array' then raise exception 'invalid_payload'; end if;
  if p_runs is not null and jsonb_typeof(p_runs) is distinct from 'array' then raise exception 'invalid_payload'; end if;

  -- Validate everything before writing anything.
  for e in select value from jsonb_array_elements(p_exercises) loop
    if jsonb_typeof(e->'sets') is distinct from 'array' then raise exception 'invalid_payload'; end if;
    select x.load_type, x.name into v_load, v_ex_name from exercises x where x.id = (e->>'exercise_id')::uuid;
    if not found then raise exception 'exercise_not_found'; end if;
    ex_ids := ex_ids || (e->>'id')::uuid;
    working_ids := '{}';
    for st in select value from jsonb_array_elements(e->'sets') loop
      set_ids := set_ids || (st->>'id')::uuid;
      v_kind := coalesce(st->>'kind', 'working');
      v_parent := (st->>'drop_parent_id')::uuid;
      if v_kind not in ('warmup', 'working', 'drop') then raise exception 'invalid_payload'; end if;
      if (v_kind = 'drop') <> (v_parent is not null) then raise exception 'invalid_drop' using detail = v_ex_name; end if;
      if v_kind = 'drop' and not (v_parent = any(working_ids)) then raise exception 'invalid_drop' using detail = v_ex_name; end if;
      if v_kind = 'working' then working_ids := working_ids || (st->>'id')::uuid; end if;
      v_sided := coalesce((st->>'sided')::boolean, false);
      if not v_sided then
        v_reps := (st->>'reps')::integer;
        if v_reps is null or v_reps < 1 then raise exception 'missing_reps' using detail = v_ex_name; end if;
        if v_load = 'assisted' and st->>'assistance_kg' is null then raise exception 'missing_assistance' using detail = v_ex_name; end if;
        if v_load = 'external' and st->>'weight_kg' is null then raise exception 'missing_weight' using detail = v_ex_name; end if;
      else
        v_l := coalesce((st->>'left_completed')::boolean, false);
        v_r := coalesce((st->>'right_completed')::boolean, false);
        if not (v_l or v_r) then raise exception 'missing_side' using detail = v_ex_name; end if;
        foreach v_side in array array['left', 'right'] loop
          if (v_side = 'left' and not v_l) or (v_side = 'right' and not v_r) then continue; end if;
          v_reps := (st->>(v_side || '_reps'))::integer;
          if v_reps is null or v_reps < 1 then raise exception 'missing_reps' using detail = v_ex_name; end if;
          if v_load = 'assisted' and st->>(v_side || '_assistance_kg') is null then raise exception 'missing_assistance' using detail = v_ex_name; end if;
          if v_load = 'external' and st->>(v_side || '_weight_kg') is null then raise exception 'missing_weight' using detail = v_ex_name; end if;
        end loop;
      end if;
    end loop;
  end loop;
  if p_runs is not null then
    for rn in select value from jsonb_array_elements(p_runs) loop
      if jsonb_typeof(rn) is distinct from 'object' then raise exception 'invalid_payload'; end if;
      run_ids := run_ids || (rn->>'id')::uuid;
      v_dur := (rn->>'duration_s')::integer;
      v_dist := (rn->>'distance_m')::numeric;
      if v_dur is null or v_dur < 1 or v_dur > 86400 then
        raise exception 'missing_run_duration' using detail = coalesce(nullif(btrim(rn->>'name'), ''), 'Run');
      end if;
      if v_dist is not null and (v_dist <= 0 or v_dist > 500000 or v_dist > v_dur * 11) then
        raise exception 'invalid_run_distance' using detail = coalesce(nullif(btrim(rn->>'name'), ''), 'Run');
      end if;
    end loop;
  end if;
  if array_position(ex_ids, null) is not null or array_position(set_ids, null) is not null or array_position(run_ids, null) is not null
     or cardinality(ex_ids) <> (select count(distinct x) from unnest(ex_ids) x)
     or cardinality(set_ids) <> (select count(distinct x) from unnest(set_ids) x)
     or cardinality(run_ids) <> (select count(distinct x) from unnest(run_ids) x) then
    raise exception 'invalid_payload';
  end if;
  -- Ids must be new or already belong to this session. Rows of other users are invisible here
  -- and are rejected by the primary key / RLS on write.
  if exists (select 1 from session_exercises where id = any(ex_ids) and session_id <> p_session_id)
     or exists (select 1 from set_logs where id = any(set_ids) and session_id <> p_session_id)
     or exists (select 1 from session_runs where id = any(run_ids) and session_id <> p_session_id) then
    raise exception 'row_not_in_session';
  end if;

  delete from set_logs where session_id = p_session_id and id <> all(set_ids);
  delete from session_exercises where session_id = p_session_id and id <> all(ex_ids);
  if p_runs is not null then
    delete from session_runs where session_id = p_session_id and id <> all(run_ids);
  end if;
  update workout_sessions
     set name = v_name, notes = nullif(p_session->>'notes', ''), started_at = v_start, ended_at = v_end,
         shortfall_reason = case when p_session ? 'shortfall_reason' then nullif(p_session->>'shortfall_reason', '') else shortfall_reason end
   where id = p_session_id;

  for e, e_pos in select value, ordinality - 1 from jsonb_array_elements(p_exercises) with ordinality loop
    insert into session_exercises (id, session_id, exercise_id, position, prescribed, notes, track_sides, attachment_state, attachment_id)
    values ((e->>'id')::uuid, p_session_id, (e->>'exercise_id')::uuid, coalesce((e->>'position')::integer, e_pos),
            coalesce(e->'prescribed', '{}'::jsonb), nullif(e->>'notes', ''),
            coalesce((e->>'track_sides')::boolean, false), e->>'attachment_state', (e->>'attachment_id')::uuid)
    on conflict (id) do update
      set exercise_id = excluded.exercise_id, position = excluded.position,
          prescribed = excluded.prescribed, notes = excluded.notes,
          track_sides = case when e ? 'track_sides' then excluded.track_sides else session_exercises.track_sides end,
          attachment_state = case when e ? 'attachment_state' then excluded.attachment_state else session_exercises.attachment_state end,
          attachment_id = case when e ? 'attachment_state' then excluded.attachment_id else session_exercises.attachment_id end;
    for st, st_pos in select value, ordinality - 1 from jsonb_array_elements(e->'sets') with ordinality loop
      v_sided := coalesce((st->>'sided')::boolean, false);
      v_l := v_sided and coalesce((st->>'left_completed')::boolean, false);
      v_r := v_sided and coalesce((st->>'right_completed')::boolean, false);
      insert into set_logs (id, session_id, session_exercise_id, position, kind, weight_kg, assistance_kg, reps, rir,
                            completed, completed_at, notes, sided,
                            left_weight_kg, left_assistance_kg, left_reps, left_rir, left_completed, left_completed_at,
                            right_weight_kg, right_assistance_kg, right_reps, right_rir, right_completed, right_completed_at,
                            drop_parent_id)
      values ((st->>'id')::uuid, p_session_id, (e->>'id')::uuid, st_pos,
              coalesce(st->>'kind', 'working')::public.set_kind,
              case when v_sided then null else (st->>'weight_kg')::numeric end,
              case when v_sided then null else (st->>'assistance_kg')::numeric end,
              case when v_sided then null else (st->>'reps')::smallint end,
              case when v_sided then null else (st->>'rir')::numeric end,
              true, coalesce((st->>'completed_at')::timestamptz, v_start), nullif(st->>'notes', ''), v_sided,
              case when v_l then (st->>'left_weight_kg')::numeric end, case when v_l then (st->>'left_assistance_kg')::numeric end,
              case when v_l then (st->>'left_reps')::smallint end, case when v_l then (st->>'left_rir')::numeric end,
              v_l, case when v_l then coalesce((st->>'left_completed_at')::timestamptz, (st->>'completed_at')::timestamptz, v_start) end,
              case when v_r then (st->>'right_weight_kg')::numeric end, case when v_r then (st->>'right_assistance_kg')::numeric end,
              case when v_r then (st->>'right_reps')::smallint end, case when v_r then (st->>'right_rir')::numeric end,
              v_r, case when v_r then coalesce((st->>'right_completed_at')::timestamptz, (st->>'completed_at')::timestamptz, v_start) end,
              (st->>'drop_parent_id')::uuid)
      on conflict (id) do update
        set session_exercise_id = excluded.session_exercise_id, position = excluded.position, kind = excluded.kind,
            weight_kg = excluded.weight_kg, assistance_kg = excluded.assistance_kg, reps = excluded.reps,
            rir = excluded.rir, completed = true, completed_at = excluded.completed_at, notes = excluded.notes,
            sided = excluded.sided,
            left_weight_kg = excluded.left_weight_kg, left_assistance_kg = excluded.left_assistance_kg,
            left_reps = excluded.left_reps, left_rir = excluded.left_rir,
            left_completed = excluded.left_completed, left_completed_at = excluded.left_completed_at,
            right_weight_kg = excluded.right_weight_kg, right_assistance_kg = excluded.right_assistance_kg,
            right_reps = excluded.right_reps, right_rir = excluded.right_rir,
            right_completed = excluded.right_completed, right_completed_at = excluded.right_completed_at,
            drop_parent_id = excluded.drop_parent_id;
    end loop;
  end loop;

  if p_runs is not null then
    for rn, rn_pos in select value, ordinality - 1 from jsonb_array_elements(p_runs) with ordinality loop
      begin
        insert into session_runs (id, session_id, position, name, prescribed, setting, duration_s, distance_m, effort,
                                  intervals_done, notes, completed, completed_at)
        values ((rn->>'id')::uuid, p_session_id, coalesce((rn->>'position')::integer, rn_pos),
                coalesce(nullif(btrim(rn->>'name'), ''), 'Run'),
                case when jsonb_typeof(rn->'prescribed') = 'object' then rn->'prescribed' else '{}'::jsonb end,
                rn->>'setting', (rn->>'duration_s')::integer, (rn->>'distance_m')::numeric, (rn->>'effort')::smallint,
                (rn->>'intervals_done')::smallint, nullif(rn->>'notes', ''), true,
                coalesce((rn->>'completed_at')::timestamptz, v_start))
        on conflict (id) do update
          set position = excluded.position, name = excluded.name, prescribed = excluded.prescribed,
              setting = excluded.setting, duration_s = excluded.duration_s, distance_m = excluded.distance_m,
              effort = excluded.effort, intervals_done = excluded.intervals_done, notes = excluded.notes,
              completed = true, completed_at = excluded.completed_at;
      exception
        when check_violation or invalid_text_representation or numeric_value_out_of_range then
          raise exception 'invalid_run' using detail = coalesce(nullif(btrim(rn->>'name'), ''), 'Run');
      end;
    end loop;
  end if;
end $$;
